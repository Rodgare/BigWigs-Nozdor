function mod:OnBossEnable()
	self:RegisterMessage("BigWigs_OnBossEngage", "Disable")

	self:Log("SPELL_CAST_START", "Cast",
		191100, 191104, 59011, 51240, 59010, 191105, 191106,
		191170, 191137, 191138, 191148, 13738, 191119, 191123,
