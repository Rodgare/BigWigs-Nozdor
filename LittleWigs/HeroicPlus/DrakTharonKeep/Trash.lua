end

--------------------------------------------------------------------------------
--  Event Handlers
--

local throttle = {}
function mod:Cast(args)
	local t = GetTime()
	local id = args.spellId
	if throttle[id] and t - throttle[id] < 2 then return end
	throttle[id] = t
	self:Message(id, "yellow", nil, CL.casting:format(args.spellName))
end